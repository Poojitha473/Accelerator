-- 6. Customer-wise sales
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES
FROM CUSTOMER C JOIN SALES S
ON C.CUSTOMER_ID=S.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME
ORDER BY TOTAL_SALES DESC;

-- 7. Branch-wise sales
SELECT B.BRANCH_ID,B.BRANCH_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES
FROM BRANCHES B JOIN SALES S
ON B.BRANCH_ID = S.BRANCH_ID
GROUP BY B.BRANCH_ID,B.BRANCH_NAME
ORDER BY TOTAL_SALES DESC;

-- 8. Product-wise sales
SELECT P.PRODUCT_ID,P.PRODUCT_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES
FROM PRODUCTS P JOIN SALES S
ON P.PRODUCT_ID = S.PRODUCT_ID
GROUP BY P.PRODUCT_ID,P.PRODUCT_NAME
ORDER BY TOTAL_SALES DESC;

-- 9. Category-wise sales
SELECT P.CATEGORY,SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES
FROM PRODUCTS P JOIN SALES S
ON P.PRODUCT_ID=S.PRODUCT_ID
GROUP BY P.CATEGORY
ORDER BY TOTAL_SALES DESC;

