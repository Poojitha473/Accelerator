-- PHASE 4: WINDOW FUNCTIONS
-- 1. Rank customers based on total spending
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING,RANK() OVER (
ORDER BY SUM(S.TOTAL_AMOUNT) DESC
) AS CUSTOMER_RANK
FROM CUSTOMER C JOIN SALES S
ON C.CUSTOMER_ID=S.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME
ORDER BY CUSTOMER_RANK;

-- 2. Rank branches based on total sales
SELECT B.BRANCH_ID,B.BRANCH_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES,RANK() OVER (
ORDER BY SUM(S.TOTAL_AMOUNT) DESC
) AS BRANCH_RANK
FROM BRANCHES B JOIN SALES S
ON B.BRANCH_ID = S.BRANCH_ID
GROUP BY B.BRANCH_ID,B.BRANCH_NAME
ORDER BY BRANCH_RANK;

-- 3. Top-selling product in each category
--    using ROW_NUMBER()
WITH PRODUCT_REVENUE AS(
SELECT P.PRODUCT_ID,P.PRODUCT_NAME,P.CATEGORY,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM PRODUCTS P JOIN SALES S
ON P.PRODUCT_ID=S.PRODUCT_ID
GROUP BY P.PRODUCT_ID,P.PRODUCT_NAME,P.CATEGORY
),
RANKED_PRODUCTS AS (
SELECT PRODUCT_ID,PRODUCT_NAME,CATEGORY,TOTAL_REVENUE,
ROW_NUMBER() OVER (
PARTITION BY CATEGORY
ORDER BY TOTAL_REVENUE DESC
) AS ROW_NUM
FROM PRODUCT_REVENUE
)
SELECT PRODUCT_ID,PRODUCT_NAME,CATEGORY,TOTAL_REVENUE
FROM RANKED_PRODUCTS
WHERE ROW_NUM = 1
ORDER BY CATEGORY;

-- 4. Cumulative sales using SUM() OVER()
SELECT SALE_DATE,SUM(TOTAL_AMOUNT) AS DAILY_SALES,
SUM(SUM(TOTAL_AMOUNT)) OVER (
ORDER BY SALE_DATE
) AS CUMULATIVE_SALES
FROM SALES
GROUP BY SALE_DATE
ORDER BY SALE_DATE;

-- 5. Average sale amount using AVG() OVER()
SELECT SALE_ID,SALE_DATE,TOTAL_AMOUNT,AVG(TOTAL_AMOUNT) OVER (
ORDER BY SALE_DATE
ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
) AS RUNNING_AVERAGE_SALES
FROM SALES
ORDER BY SALE_DATE;

-- PHASE 5: COMMON TABLE EXPRESSIONS (CTE)
-- 1. Customer-wise revenue using CTE
WITH CUSTOMER_REVENUE AS
(
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM CUSTOMER C JOIN SALES S
ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME
)
SELECT * FROM CUSTOMER_REVENUE
ORDER BY TOTAL_REVENUE DESC;

-- 2. Customers spending greater than average spending
WITH CUSTOMER_REVENUE AS
(SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING
FROM CUSTOMER C JOIN SALES S
ON C.CUSTOMER_ID=S.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME
),
AVERAGE_SPENDING AS
(SELECT AVG(TOTAL_SPENDING) AS AVG_CUSTOMER_SPENDING
FROM CUSTOMER_REVENUE
)
SELECT CR.CUSTOMER_ID,CR.CUSTOMER_NAME,CR.TOTAL_SPENDING
FROM CUSTOMER_REVENUE CR
CROSS JOIN AVERAGE_SPENDING A
WHERE CR.TOTAL_SPENDING > A.AVG_CUSTOMER_SPENDING
ORDER BY CR.TOTAL_SPENDING DESC;

-- PHASE 6: VIEWS
-- 1. Create SALES_REPORT view
CREATE OR REPLACE VIEW SALES_REPORT AS
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,C.CITY,C.MEMBERSHIP,
SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES
FROM CUSTOMER C JOIN SALES S
ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME,C.CITY,C.MEMBERSHIP;

-- Query SALES_REPORT
SELECT * FROM SALES_REPORT
ORDER BY TOTAL_SALES DESC;

-- 2. Create TOP_CUSTOMERS materialized view
CREATE OR REPLACE VIEW TOP_CUSTOMERS AS
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM CUSTOMER C JOIN SALES S
ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME;

-- Query TOP_CUSTOMERS
SELECT * FROM TOP_CUSTOMERS
ORDER BY TOTAL_REVENUE DESC
LIMIT 3;